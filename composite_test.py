def pick_ibd_block(gpos, segsize):
    """
    Pick a segment of size 'segsize' in centimorgans based on the given genetic
    positions.

    Args:
        gpos: a numpy vector of genetic positions (in cMs)
        segsize: A target segment size in (cMs)
    Returns:
        a mask (vector of bools) indicating whether a segment is in IBD.
    """
    ibd_start = random.uniform(gpos[0], gpos[-1] - segsize)
    return (gpos >= ibd_start) & (gpos < ibd_start + segsize)


