'''

Compares the output of tjbd run in simulation mode using VCFs generated by
ped-sim with the ground-truth IBD segments from ped-sim.

Sam Vohr (svohr@soe.ucsc.edu)
Wed Aug 21 18:31:11 PDT 2019

'''


import sys
import argparse

import pandas


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('chrom', help='Chromosome number.')
    parser.add_argument('pedsim_segs_fn', help='Truth segments from ped-sim.')
    parser.add_argument('tjbd_segs_fn', help='Detected segments from tjbd.')
    parser.add_argument('tjbd_pos_fn', help='Positional output from tjbd.')

    args = parser.parse_args()

    pedsim_segs_df = pandas.read_csv(args.pedsim_segs_fn,
                                     sep='\t',
                                     names=['iid1', 'iid2',
                                            'chrom', 'start', 'end',
                                            'ibd', 'start_cm', 'end_cm',
                                            'size_cm'])
    pedsim_segs_df = pedsim_segs_df[pedsim_segs_df['chrom'] == chrom]

    tjbd_segs_df = pandas.read_csv(args.tjbd_segs_fn, sep='\t')
    tjbd_pos_df = pandas.read_csv(args.tjbd_pos_fn, sep='\t')

    tjbd_pos_fn['ibd_pedsim'] = False

    for _, seg in pedsim_segs_df.iterrows():
        seg_mask = (tjbd_pos_fn['pos'] >= seg['start']
                    & tjbd_pos_fn['pos'] <= seg['end'])
        tjbd_pos_df.loc[seg_mask, 'ibd_pedsim'] = True

        segment_tp += tjbd_pos_df.loc[seg_mask, 'ibd_call'].any()
        segment_fn += not tjbd_pos_df.loc[seg_mask, 'ibd_call'].any()

    for _, seg in tjbd_segs_df.iterrows():
        seg_mask = (tjbd_pos_fn['pos'] >= seg['start']
                    & tjbd_pos_fn['pos'] <= seg['end'])
        segment_fp += not tjbd_pos_df.loc[seg_mask, 'ibd_pedsim'].any()

    # Stuff to measure
    # Segments:
    # # of True Positives
    # # of True Negatives
    # # of False Positives
    # # of False Negatives

    # Positions:
    # # of True Positives (positions correctly called IBD)
    # # of True Negatives (positions correctly called no-IBD)
    # # of False Positives
    # # of False Negatives

    # True number of segments
    # Detected number of segments
    # True total IBD
    # Detected total IBD

    return 0


if __name__ == '__main__':
    sys.exit(main())
